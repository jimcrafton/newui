// mvc1 - a minimal, real, end-to-end MVC demo: two Models (StringListModel/
// StringTreeModel) driving a ListView and a TreeView (controls.h) via
// ListController/TreeController - the same Model/Controller/Item
// foundation items-plan.md (repo root) asked for, exercised on screen: a
// real scrollable, clickable list and a real expandable, clickable tree.
// See HANDOFF.md Parts 58-64 for the implementation history behind
// ListView/TreeView/ListController/TreeController/ListItem/TreeItem/
// Model::size()/TreeModel::childCount().

