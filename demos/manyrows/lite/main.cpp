// manyrows_lite - the table demo with nothing around it: a TimedTableView over 1,000,000 generated rows
// and a status bar (paint time, visible rows, selection). It exists to show how little it takes to put a
// virtualized table on screen; the full app (manyrows) adds the menus, the formula bar and file I/O.
//
// SpreadsheetController attaches to the bare table, so editing (F2, double-click or just typing), undo,
// copy / cut / paste, fill and Delete all work through the keyboard. There is no File menu - nothing here
// reads or writes a file, and no DocumentController is involved.
//
// `manyrows_lite.exe --check` loads and lays out the window, prints the model shape, then exits.

#include "newui/newui.h"
#include "newui/application.h"
#include "newui/bundle.h"
#include "newui/controls.h"
#include "newui/frame.h"
#include "newui/rootview.h"

#include "manyrowsmodel.h"
#include "spreadsheetcontroller.h"
#include "timedtableview.h"

#include <cstdio>
#include <memory>
#include <string>

// Both generated by reflectgen - newui's own classes first (TimedTableView derives from them).
extern void registerReflectionData();
extern void registerManyRowsReflection();

int main(int argc, char** argv) {
    registerReflectionData();
    registerManyRowsReflection();

    bool checkOnly = argc > 1 && std::string(argv[1]) == "--check";

    newui::Frame frame;
    newui::Application& app = newui::Application::instance();
    app.setName("manyrows_lite");
    app.setFrame(&frame);

    frame.setName("manyrows_lite");   // -> Resources/manyrows_lite.newui
    if (!newui::Bundle::instance().loadFrame(frame)) {
        std::printf("manyrows_lite: could not load Resources/manyrows_lite.newui\n");
        return 1;
    }
    auto* table = dynamic_cast<manyrows::TimedTableView*>(frame.rootView().findView("table"));
    auto* status = dynamic_cast<newui::StatusBar*>(frame.rootView().findView("statusBar"));
    if (table == nullptr || status == nullptr) {
        std::printf("manyrows_lite: manyrows_lite.newui is missing the table or the status bar\n");
        return 1;
    }

    // Items are built by class name through reflection (CellItem - column-aware typography).
    table->controller().setDefaultItemClassName("CellItem");
    auto ownedModel = std::make_unique<manyrows::ManyRowsModel>();   // 1,000,000 rows, computed not stored
    manyrows::ManyRowsModel* model = ownedModel.get();
    table->setModel(std::move(ownedModel));

    if (checkOnly) {
        frame.rootView().updateLayout();
        std::printf("model: %zu rows x %zu columns\n", model->rowCount(), model->columnCount());
        return 0;
    }

    manyrows::SpreadsheetController spreadsheet(*table, *model);   // must outlive app.run()
    spreadsheet.setStatusBar(status);
    spreadsheet.say("Click a cell; F2 or type to edit; Alt+Up / Alt+Down sort by its column; Ctrl+Shift+F filters to its value; Alt+Backspace resets");

    app.run();
    return 0;
}
