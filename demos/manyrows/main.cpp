// manyrows - million-row table demo (see demos/PLAN.md).
//
// Loads Resources/manyrows.newui and hands the window to ManyRowsWindow, which connects the two controllers
// that do the work: SpreadsheetController (the cells) and ManyRowsController (the file, a DocumentController).
// main() only builds, optionally opens the file named on the command line, and runs.
//
// `manyrows.exe file.csv` opens that file instead of the sample table.
// `manyrows.exe --check` loads, lays out, prints the view tree and the model shape, then exits (smoke test).

#include "newui/newui.h"
#include "newui/application.h"
#include "newui/bundle.h"
#include "newui/frame.h"
#include "newui/rootview.h"

#include "manyrowswindow.h"

#include <cstdio>
#include <exception>
#include <string>
#include <typeinfo>

// Both generated by reflectgen - newui's own classes first (TimedTableView derives from them).
extern void registerReflectionData();
extern void registerManyRowsReflection();

namespace {
    void dumpTree(const newui::View& view, int depth, int maxDepth) {
        const newui::Rect& b = view.bounds();
        std::printf("%*s%s \"%s\" [%.0f,%.0f %.0fx%.0f]\n", depth * 2, "", typeid(view).name(), view.name().c_str(), b.left(),
            b.top(), b.width(), b.height());
        if (depth >= maxDepth) {
            return;
        }
        for (const newui::SubView* child : view.childViews()) {
            dumpTree(*child, depth + 1, maxDepth);
        }
    }
}

int main(int argc, char** argv) {
    registerReflectionData();
    registerManyRowsReflection();

    std::string startupPath;
    bool checkOnly = false;
    int checkDepth = 4;
    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg == "--check") {
            checkOnly = true;
        } else if (arg.rfind("--depth=", 0) == 0) {
            checkDepth = std::stoi(arg.substr(8));
        } else if (startupPath.empty() && arg.rfind("--", 0) != 0) {
            startupPath = arg;
        }
    }

    newui::Frame frame;
    newui::Application& app = newui::Application::instance();
    app.setName("manyrows");
    app.setFrame(&frame);

    frame.setName("manyrows");
    if (!newui::Bundle::instance().loadFrame(frame)) {
        std::printf("manyrows: could not load Resources/manyrows.newui\n");
        return 1;
    }

    try {
        manyrows::ManyRowsWindow window(frame);   // must outlive app.run(): the views call back into it

        if (checkOnly) {
            frame.rootView().updateLayout();
            dumpTree(frame.rootView(), 0, checkDepth);
            std::printf("model: %zu rows x %zu columns; %s = \"%s\"\n", window.table().controller().rowCount(),
                window.table().controller().columnCount(), manyrows::SpreadsheetEditor::cellName(999999, 9).c_str(),
                window.model().cellText(999999, 9).c_str());
            return 0;
        }
        if (!startupPath.empty()) {
            window.openOnStart(startupPath);
        }
        app.run();
    } catch (const std::exception& e) {
        std::printf("manyrows: %s\n", e.what());
        return 1;
    }
    return 0;
}
