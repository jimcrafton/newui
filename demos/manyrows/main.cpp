// manyrows - million-row table demo (see demos/PLAN.md).
//
// Loads Resources/manyrows.newui (menu bar, a TimedTableView in a ScrollView, status bar), gives the
// table a ManyRowsModel of 1,000,000 generated rows and keeps the status bar's panes current:
//   0 message   1 paint time (last / smoothed / worst, ms)   2 visible rows   3 selection   4 total rows
// `manyrows.exe --check` loads, lays out, prints the tree and the model shape, then exits (smoke test).

#include "newui/newui.h"
#include "newui/application.h"
#include "newui/bundle.h"
#include "newui/controls.h"
#include "newui/frame.h"
#include "newui/menus.h"
#include "newui/rootview.h"
#include "newui/runloop.h"

#include "manyrowscontroller.h"
#include "manyrowsdocument.h"
#include "manyrowsmodel.h"
#include "spreadsheeteditor.h"
#include "timedtableview.h"

#include "newui/keyboard_constants.h"
#include "newui/utils.h"

#include <cstdio>
#include <functional>
#include <string>
#include <typeinfo>
#include <vector>

// Both generated by reflectgen - newui's own classes first (TimedTableView derives from them).
extern void registerReflectionData();
extern void registerManyRowsReflection();

namespace {
    // Status bar pane indices, in manyrows.newui order.
    constexpr std::size_t kMessagePane = 0;
    constexpr std::size_t kPaintPane = 1;
    constexpr std::size_t kRowsPane = 2;
    constexpr std::size_t kSelectionPane = 3;
    constexpr std::size_t kTotalPane = 4;

    void dumpTree(const newui::View& view, int depth, int maxDepth) {
        const newui::Rect& b = view.bounds();
        std::printf("%*s%s \"%s\" [%.0f,%.0f %.0fx%.0f]\n", depth * 2, "", typeid(view).name(), view.name().c_str(), b.left(),
            b.top(), b.width(), b.height());
        if (depth >= maxDepth) {
            return;
        }
        for (const newui::SubView* child : view.childViews()) {
            dumpTree(*child, depth + 1, maxDepth);
        }
    }

    // 0 -> "A", 25 -> "Z", 26 -> "AA" - the spreadsheet column letters TableView paints for untitled columns.
    std::string columnLetters(std::size_t column) {
        std::string letters;
        for (std::size_t n = column + 1; n > 0; n = (n - 1) / 26) {
            letters.insert(letters.begin(), char('A' + (n - 1) % 26));
        }
        return letters;
    }

    std::string cellName(std::size_t row, std::size_t column) {
        return columnLetters(column) + std::to_string(row + 1);
    }

    // 1234567 -> "1,234,567".
    std::string withCommas(std::size_t value) {
        std::string digits = std::to_string(value);
        for (std::ptrdiff_t i = std::ptrdiff_t(digits.size()) - 3; i > 0; i -= 3) {
            digits.insert(std::size_t(i), ",");
        }
        return digits;
    }

    std::string millis(double ms) {
        char buffer[32];
        std::snprintf(buffer, sizeof(buffer), "%.1f", ms);
        return buffer;
    }
}

int main(int argc, char** argv) {
    registerReflectionData();
    registerManyRowsReflection();

    std::string startupPath;
    bool checkOnly = false;
    int checkDepth = 4;
    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg == "--check") {
            checkOnly = true;
        } else if (arg.rfind("--depth=", 0) == 0) {
            checkDepth = std::stoi(arg.substr(8));
        } else if (startupPath.empty() && arg.rfind("--", 0) != 0) {
            startupPath = arg;
        }
    }

    newui::Frame frame;
    newui::Application& app = newui::Application::instance();
    app.setName("manyrows");
    app.setFrame(&frame);

    frame.setName("manyrows");
    if (!newui::Bundle::instance().loadFrame(frame)) {
        std::printf("manyrows: could not load Resources/manyrows.newui\n");
        return 1;
    }

    auto* table = dynamic_cast<manyrows::TimedTableView*>(frame.rootView().findView("table"));
    auto* status = dynamic_cast<newui::StatusBar*>(frame.rootView().findView("statusBar"));
    if (table == nullptr || status == nullptr) {
        std::printf("manyrows: manyrows.newui is missing the table or the status bar\n");
        return 1;
    }
    // Items are built by class name through reflection (CellItem - column-aware typography).
    table->controller().setDefaultItemClassName("CellItem");
    auto ownedModel = std::make_unique<manyrows::ManyRowsModel>();
    manyrows::ManyRowsModel* model = ownedModel.get();
    table->setModel(std::move(ownedModel));

    if (checkOnly) {
        frame.rootView().updateLayout();
        dumpTree(frame.rootView(), 0, checkDepth);
        std::printf("model: %zu rows x %zu columns; %s = \"%s\"\n", table->controller().rowCount(),
            table->controller().columnCount(), cellName(999999, 9).c_str(),
            std::any_cast<std::string>(table->model()->valueAt(999999, 9)).c_str());
        return 0;
    }

    // Status bar panes (see the header comment). Painting updates them, so scrolling keeps them live;
    // setPaneText marks only that pane dirty, so this is cheap enough to run on every paint.
    status->setPaneText(kTotalPane, withCommas(table->controller().rowCount()) + " rows");

    table->onPainted += [status](manyrows::TimedTableView& view) {
        status->setPaneText(kPaintPane, "paint " + millis(view.lastPaintMs()) + " / " + millis(view.smoothedPaintMs()) + " / " +
                                            millis(view.worstPaintMs()) + " ms");
        std::size_t count = view.visibleRowCount();
        if (count == 0) {
            status->setPaneText(kRowsPane, "rows -");
        } else {
            std::size_t first = view.firstVisibleRow();
            status->setPaneText(kRowsPane, "rows " + withCommas(first + 1) + "-" + withCommas(first + count));
        }
        return newui::SyncReturn::Handled;
    };

    table->onSelectionChanged += [status](newui::TableView& view) {
        std::optional<newui::CellRange> range = view.selectedRange();
        if (!range.has_value()) {
            status->setPaneText(kSelectionPane, "no selection");
            return newui::SyncReturn::Handled;
        }
        std::string text = cellName(range->firstRow, range->firstColumn);
        std::size_t cells = range->rowCount() * range->columnCount();
        if (cells > 1) {
            text += ":" + cellName(range->lastRow, range->lastColumn) + "  (" + withCommas(cells) + " cells)";
        }
        status->setPaneText(kSelectionPane, text);
        return newui::SyncReturn::Handled;
    };

    // Formula bar: the name box shows the active cell, the field its text; Enter in the field edits the cell.
    auto* nameBox = dynamic_cast<newui::TextField*>(frame.rootView().findView("nameBox"));
    auto* formulaField = dynamic_cast<newui::TextField*>(frame.rootView().findView("formulaField"));
    if (nameBox != nullptr) {
        nameBox->controller().inputTraits().setReadOnly(true);
    }
    auto syncFormulaBar = [table, model, nameBox, formulaField]() {
        if (nameBox == nullptr || formulaField == nullptr) {
            return;
        }
        if (!table->hasActiveCell()) {
            nameBox->setText(L"");
            formulaField->setText(L"");
            return;
        }
        nameBox->setText(newui::utf8ToWide(cellName(table->activeRow(), table->activeColumn())));
        formulaField->setText(newui::utf8ToWide(model->cellText(table->activeRow(), table->activeColumn())));
    };
    table->onSelectionChanged += [syncFormulaBar](newui::TableView&) {
        syncFormulaBar();
        return newui::SyncReturn::Handled;
    };
    model->onChanged += [syncFormulaBar](newui::Model&) {
        syncFormulaBar();
        return newui::SyncReturn::Ignored;
    };

    // The file behind the table, and its File menu logic. Static so the handlers below capture little.
    static manyrows::ManyRowsDocument document(*model);
    static manyrows::ManyRowsController files(document, frame);

    // Edits and undo. Static so the handlers below capture little and the history lives for the whole run.
    static manyrows::SpreadsheetEditor editor(*model);
    auto setMessage = [status](const std::string& text) { status->setPaneText(kMessagePane, text); };

    // The one path for every typed value (in-cell editor and formula bar): validate, then apply.
    auto commitCell = [setMessage, model](std::size_t row, std::size_t column, const std::string& typed) {
        if (files.isBusy()) {
            setMessage(files.busyVerb() + " " + files.busyFileName() + " - editing resumes when it finishes");
            return false;
        }
        std::string text = typed;
        // The typed schema (Qty a whole number, Status one of five...) belongs to the generated table; a
        // loaded file accepts any text.
        std::string error = model->isGenerated() ? manyrows::SpreadsheetEditor::validate(column, text) : std::string();
        if (!error.empty()) {
            setMessage(cellName(row, column) + ": " + error);
            return false;
        }
        editor.setCell(row, column, text);
        return true;
    };
    table->setCommitHandler(commitCell);
    if (formulaField != nullptr) {
        formulaField->onReturnPressed += [table, commitCell, formulaField](newui::TextField&) {
            if (table->hasActiveCell() &&
                commitCell(table->activeRow(), table->activeColumn(), newui::wideToUtf8(formulaField->text()))) {
                if (auto* root = table->rootView()) {
                    root->setFocusedSubView(table);
                }
            }
            return newui::SyncReturn::Handled;
        };
    }

    // Undo/redo move the selection to the cells they changed.
    editor.onReplayed = [table](const newui::CellRange& block) {
        table->setActiveCell(block.firstRow, block.firstColumn);
        if (block.lastRow > block.firstRow || block.lastColumn > block.firstColumn) {
            table->setActiveCell(block.lastRow, block.lastColumn, true);
        }
    };
    auto* menuBar = dynamic_cast<newui::MenuBar*>(frame.rootView().findView("menuBar"));
    auto onItem = [menuBar](const char* menuName, const char* text, std::function<void(newui::MenuItem&)> action) {
        if (menuBar == nullptr) {
            return;
        }
        for (newui::MenuItem* menu : menuBar->menus()) {
            if (menu->text() != menuName) {
                continue;
            }
            for (newui::MenuItem* item : menu->children()) {
                if (item->text() == text) {
                    item->onClick += [action](newui::MenuItem& clicked) {
                        action(clicked);
                        return newui::SyncReturn::Handled;
                    };
                    return;
                }
            }
        }
    };
    // Edit > Undo / Redo show what they would act on.
    auto syncHistory = [menuBar]() {
        if (menuBar == nullptr) {
            return;
        }
        for (newui::MenuItem* menu : menuBar->menus()) {
            if (menu->text() != "Edit") {
                continue;
            }
            for (newui::MenuItem* item : menu->children()) {
                if (item->text().rfind("Undo", 0) == 0) {
                    item->setText(editor.canUndo() ? "Undo " + editor.undoDescription() : "Undo");
                    item->state().setEnabled(editor.canUndo());
                } else if (item->text().rfind("Redo", 0) == 0) {
                    item->setText(editor.canRedo() ? "Redo " + editor.redoDescription() : "Redo");
                    item->state().setEnabled(editor.canRedo());
                }
            }
        }
    };
    editor.onHistoryChanged = syncHistory;
    syncHistory();
    auto doUndo = [setMessage]() {
        if (editor.canUndo() && !files.isBusy()) {
            std::string what = editor.undoDescription();
            editor.undo();
            setMessage("Undid " + what);
        }
    };
    auto doRedo = [setMessage]() {
        if (editor.canRedo() && !files.isBusy()) {
            std::string what = editor.redoDescription();
            editor.redo();
            setMessage("Redid " + what);
        }
    };
    auto doClear = [table, setMessage]() {
        std::optional<newui::CellRange> range = table->selectedRange();
        if (!range.has_value() || files.isBusy()) {
            return;
        }
        if (!editor.clearRange(*range)) {
            setMessage("Nothing cleared (already blank, or more than " + withCommas(manyrows::SpreadsheetEditor::kMaxRangeCells) + " cells)");
        }
    };
    // Menu items are found by text; their first word is what the syncHistory above keys on.
    onItem("Edit", "Undo", [doUndo](newui::MenuItem&) { doUndo(); });
    onItem("Edit", "Redo", [doRedo](newui::MenuItem&) { doRedo(); });
    onItem("Edit", "Clear Cells", [doClear](newui::MenuItem&) { doClear(); });
    onItem("Edit", "Edit Cell", [table](newui::MenuItem&) { table->beginEdit(); });
    table->onKeyDown += [doUndo, doRedo, doClear](newui::View&, std::uint32_t keyMask, int, int, std::uint32_t vkey) {
        bool ctrl = (keyMask & newui::kmCtrl) != 0;
        if (ctrl && vkey == newui::vkLetterZ) { doUndo(); return newui::SyncReturn::Handled; }
        if (ctrl && vkey == newui::vkLetterY) { doRedo(); return newui::SyncReturn::Handled; }
        bool shift = (keyMask & newui::kmShift) != 0;
        if (ctrl && vkey == newui::vkLetterN) { files.newDocument(); return newui::SyncReturn::Handled; }
        if (ctrl && vkey == newui::vkLetterO) { files.open(); return newui::SyncReturn::Handled; }
        if (ctrl && vkey == newui::vkLetterS) {
            if (shift) { files.saveAs(); } else { files.save(); }
            return newui::SyncReturn::Handled;
        }
        if (vkey == newui::vkDelete) { doClear(); return newui::SyncReturn::Handled; }
        return newui::SyncReturn::Ignored;
    };
    // ---- File menu: New / Open / Save / Save As / Sample Data, the title bar, and the "save changes?" question ----
    static bool replacing = false;
    auto updateTitle = [&frame]() { frame.setTitle("manyrows - " + files.displayName()); };
    files.onStateChanged += [updateTitle](manyrows::ManyRowsController&) {
        updateTitle();
        return newui::SyncReturn::Handled;
    };
    files.onStatus += [setMessage](manyrows::ManyRowsController&, std::string text) {
        setMessage(text);
        return newui::SyncReturn::Handled;
    };
    // New content: the old undo history, selection and formula bar no longer apply.
    files.onDocumentReplaced += [table, model, status, syncFormulaBar](manyrows::ManyRowsController&) {
        replacing = true;   // clearing the history is not an edit
        editor.reset();
        replacing = false;
        table->clearSelection();
        syncFormulaBar();
        status->setPaneText(kTotalPane, withCommas(model->rowCount()) + " rows x " + std::to_string(model->columnCount()) + " cols");
        return newui::SyncReturn::Handled;
    };
    // Any change to the cells (typing, clearing, undo, redo) makes the file modified.
    auto previousHistoryHook = editor.onHistoryChanged;
    editor.onHistoryChanged = [previousHistoryHook]() {
        if (previousHistoryHook) {
            previousHistoryHook();
        }
        if (!replacing) {
            // Undoing back to the saved step makes the file clean again; any other step makes it modified.
            if (editor.isAtSavedState()) {
                document.markUnmodified();
            } else {
                document.markModified();
            }
        }
    };
    // Whenever the document becomes clean (saved, loaded, undone back) the history's current step is the saved one.
    document.onModifiedChanged += [](newui::Document&) {
        if (!document.isModified()) {
            editor.markSaved();
        }
        return newui::SyncReturn::Handled;
    };
    onItem("File", "New", [](newui::MenuItem&) { files.newDocument(); });
    onItem("File", "Open...", [](newui::MenuItem&) { files.open(); });
    onItem("File", "Save", [](newui::MenuItem&) { files.save(); });
    onItem("File", "Save As...", [](newui::MenuItem&) { files.saveAs(); });
    onItem("File", "Sample Data (1M rows)", [](newui::MenuItem&) { files.sampleData(); });
    frame.onClosing += [](newui::Frame&, bool& canClose) {
        canClose = files.canClose();
        return newui::SyncReturn::Handled;
    };
    // Loading and saving run on a worker thread; the strip above the status bar shows how far it is and can cancel it.
    auto* loadStrip = frame.rootView().findView("loadStrip");
    auto* loadLabel = dynamic_cast<newui::Label*>(frame.rootView().findView("loadLabel"));
    auto* loadProgress = dynamic_cast<newui::Progress*>(frame.rootView().findView("loadProgress"));
    auto* loadCancel = dynamic_cast<newui::Button*>(frame.rootView().findView("loadCancel"));
    auto showProgress = [loadLabel, loadProgress, status]() {
        float fraction = files.busyFraction();
        if (loadProgress != nullptr) {
            loadProgress->setValue(fraction);
        }
        std::string text = files.busyVerb() + " " + files.busyFileName() + " - " + std::to_string(int(fraction * 100.0f)) + "%  (" +
                           withCommas(files.busyRows()) + " rows)";
        if (loadLabel != nullptr) {
            loadLabel->setText(text);
        }
        status->setPaneText(kTotalPane, withCommas(files.busyRows()) + " rows...");
    };
    files.onBusyStarted += [loadStrip, showProgress](manyrows::ManyRowsController&) {
        if (loadStrip != nullptr) {
            loadStrip->setVisible(true);
        }
        showProgress();
        return newui::SyncReturn::Handled;
    };
    files.onBusyProgress += [showProgress](manyrows::ManyRowsController&) {
        showProgress();
        return newui::SyncReturn::Handled;
    };
    // A workbook with several sheets: the strip swaps to a picker until the user chooses (or cancels).
    auto* sheetStrip = frame.rootView().findView("sheetStrip");
    auto* sheetLabel = dynamic_cast<newui::Label*>(frame.rootView().findView("sheetLabel"));
    auto* sheetCombo = dynamic_cast<newui::DropDownList*>(frame.rootView().findView("sheetCombo"));
    auto* sheetOpen = dynamic_cast<newui::Button*>(frame.rootView().findView("sheetOpen"));
    auto* sheetCancel = dynamic_cast<newui::Button*>(frame.rootView().findView("sheetCancel"));
    files.onSheetNeeded += [loadStrip, sheetStrip, sheetLabel, sheetCombo](manyrows::ManyRowsController&) {
        if (sheetStrip == nullptr || sheetCombo == nullptr) {
            files.chooseSheet(0);   // no picker in this layout: the first sheet
            return newui::SyncReturn::Handled;
        }
        auto items = std::make_unique<newui::StringListModel>();
        for (const std::string& name : files.sheetNames()) {
            items->addItem(name);
        }
        sheetCombo->setModel(std::move(items));
        sheetCombo->setSelectedIndex(std::size_t(0));
        if (sheetLabel != nullptr) {
            sheetLabel->setText(files.busyFileName() + " has " + std::to_string(files.sheetNames().size()) + " sheets - open:");
        }
        if (loadStrip != nullptr) {
            loadStrip->setVisible(false);
        }
        sheetStrip->setVisible(true);
        return newui::SyncReturn::Handled;
    };
    if (sheetOpen != nullptr) {
        sheetOpen->onClick += [loadStrip, sheetStrip, sheetCombo](newui::Control&) {
            std::optional<std::size_t> picked = sheetCombo != nullptr ? sheetCombo->selectedIndex() : std::nullopt;
            if (sheetStrip != nullptr) {
                sheetStrip->setVisible(false);
            }
            if (loadStrip != nullptr) {
                loadStrip->setVisible(true);
            }
            files.chooseSheet(picked.has_value() ? *picked : 0);
            return newui::SyncReturn::Handled;
        };
    }
    if (sheetCancel != nullptr) {
        sheetCancel->onClick += [](newui::Control&) {
            files.cancelBusy();   // also hides the picker (onBusyFinished)
            return newui::SyncReturn::Handled;
        };
    }
    files.onBusyFinished += [loadStrip, sheetStrip, status, model](manyrows::ManyRowsController&) {
        if (sheetStrip != nullptr) {
            sheetStrip->setVisible(false);
        }
        if (loadStrip != nullptr) {
            loadStrip->setVisible(false);
        }
        status->setPaneText(kTotalPane, withCommas(model->rowCount()) + " rows x " + std::to_string(model->columnCount()) + " cols");
        return newui::SyncReturn::Handled;
    };
    if (loadCancel != nullptr) {
        loadCancel->onClick += [](newui::Control&) {
            files.cancelBusy();
            return newui::SyncReturn::Handled;
        };
    }
    updateTitle();
    status->setPaneText(kTotalPane, withCommas(model->rowCount()) + " rows x " + std::to_string(model->columnCount()) + " cols");

    onItem("File", "Exit", [](newui::MenuItem&) {
        if (files.canClose()) {
            newui::RunLoop::current().quit();
        }
    });
    onItem("Edit", "Select All", [table](newui::MenuItem&) { table->selectAll(); });
    onItem("View", "Show Headers", [table](newui::MenuItem& item) {
        table->setHeadersVisible(!table->headersVisible());
        item.setChecked(table->headersVisible());
    });
    onItem("View", "Reset Render Stats", [table](newui::MenuItem&) { table->resetPaintStats(); });

    status->setPaneText(kMessagePane, "Click a cell; F2, double-click or type to edit; Del clears; Ctrl+Z / Ctrl+Y undo / redo; Shift extends the selection");

    // `manyrows.exe file.csv` opens that file instead of the sample table.
    if (!startupPath.empty()) {
        newui::RunLoop::current().onStart += [startupPath](newui::RunLoop&) {
            files.open(startupPath);   // starts the worker and its progress timer, which need the running loop
            return newui::SyncReturn::Handled;
        };
    }

    app.run();
    return 0;
}
