// sketch - vector editor demo (see demos/PLAN.md).
//
// S0 scaffold: loads Resources/sketch.newui (the whole window - menus, toolbars, canvas, panels,
// status bar, generated from demos/sketch/mockup/sketch-mockup.html by tools/gen_newui.py) and
// shows it. Everything interactive arrives phase by phase; what is wired here is just startup:
// `sketch.exe [file.svg]` records the path to open (opening itself lands with S4's SVG reader);
// `sketch.exe --check` loads, lays out and prints the view tree (--depth=N, default 4), then exits.

#include "newui/newui.h"
#include "newui/application.h"
#include "newui/bundle.h"
#include "newui/controls.h"
#include "newui/frame.h"
#include "newui/rootview.h"

#include "canvasview.h"
#include "sketchdocument.h"

#include "newui/menus.h"

#include <cmath>
#include <cstdio>
#include <functional>
#include <optional>
#include <string>
#include <vector>
#include <typeinfo>

// Both generated by reflectgen - nothing calls them automatically for a standalone exe. newui's
// own classes first (sketch's classes derive from them), then sketch's.
extern void registerReflectionData();
extern void registerSketchReflection();

namespace {
    // Prints the loaded view tree (class, name, bounds) down to maxDepth - what --check shows, to
    // confirm sketch.newui loaded into the structure the mockup describes and laid out sensibly.
    void dumpTree(const newui::View& view, int depth, int maxDepth) {
        const newui::Rect& b = view.bounds();
        std::printf("%*s%s \"%s\" [%.0f,%.0f %.0fx%.0f]%s\n", depth * 2, "", typeid(view).name(),
            view.name().c_str(), b.left(), b.top(), b.width(), b.height(), view.isVisible() ? "" : " (hidden)");
        if (depth >= maxDepth) {
            return;
        }
        for (const newui::SubView* child : view.childViews()) {
            dumpTree(*child, depth + 1, maxDepth);
        }
    }
}

int main(int argc, char** argv) {
    registerReflectionData();
    registerSketchReflection();

    std::string startupPath;
    bool checkOnly = false;
    bool checkTools = false;
    int checkDepth = 4;
    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg == "--check") {
            checkOnly = true;
        } else if (arg == "--check-tools") {
            checkTools = true;
        } else if (arg.rfind("--depth=", 0) == 0) {
            checkDepth = std::stoi(arg.substr(8));
        } else if (startupPath.empty()) {
            startupPath = arg;
        }
    }

    newui::Frame frame;

    newui::Application& app = newui::Application::instance();
    app.setName("sketch");
    app.setFrame(&frame);

    // Bundle::loadFrame() resolves "Resources/<frame name>.newui" next to the exe; CMake copies
    // demos/sketch/Resources there after each build.
    frame.setName("sketch");
    if (!newui::Bundle::instance().loadFrame(frame)) {
        std::printf("sketch: could not load Resources/sketch.newui\n");
        return 1;
    }

    if (checkOnly) {
        // Smoke test: load, lay out, print the tree, exit without entering the message loop.
        frame.rootView().updateLayout();
        dumpTree(frame.rootView(), 0, checkDepth);

        // The New Document dialog is a separate Frame (Resources/newdocument.newui).
        newui::Frame dialog;
        dialog.setName("newdocument");
        if (!newui::Bundle::instance().loadFrame(dialog)) {
            std::printf("sketch: could not load Resources/newdocument.newui\n");
            return 1;
        }
        std::printf("--- newdocument ---\n");
        dialog.rootView().updateLayout();
        dumpTree(dialog.rootView(), 0, checkDepth);
        return 0;
    }

    // S1: a hard-coded scene on the canvas. S4 replaces this with SketchDocument::load(startupPath).
    sketch::SketchDocument document;
    document.buildDemoScene();
    if (auto* canvas = dynamic_cast<sketch::CanvasView*>(frame.rootView().findView("canvas"))) {
        canvas->setDocument(&document);

        // Zoom combo <-> canvas <-> status bar (last pane). Combo rows: 25/50/100/200/400 %, Fit page.
        auto* zoomCombo = dynamic_cast<newui::DropDownList*>(frame.rootView().findView("zoomCombo"));
        auto* status = dynamic_cast<newui::StatusBar*>(frame.rootView().findView("statusBar"));
        static const float kZoomSteps[] = {0.25f, 0.5f, 1.0f, 2.0f, 4.0f};
        if (zoomCombo != nullptr) {
            zoomCombo->onSelectionChanged += [canvas](newui::DropDownList& combo) {
                std::optional<std::size_t> index = combo.selectedIndex();
                if (!index.has_value()) {
                    return newui::SyncReturn::Ignored;
                }
                if (*index < 5) {
                    canvas->setZoom(kZoomSteps[*index]);
                } else {
                    canvas->zoomToFit();
                }
                return newui::SyncReturn::Handled;
            };
        }
        canvas->onZoomChanged += [status, zoomCombo](sketch::CanvasView& view) {
            if (status != nullptr) {
                status->setPaneText(status->paneCount() - 1, std::to_string(int(view.zoom() * 100.0f + 0.5f)) + "%");
            }
            // Keep the combo on the matching preset (or none, for wheel/fit zooms in between).
            if (zoomCombo != nullptr) {
                std::optional<std::size_t> match;
                for (std::size_t i = 0; i < 5; ++i) {
                    if (std::fabs(view.zoom() - kZoomSteps[i]) < 1e-4f) {
                        match = i;
                    }
                }
                if (zoomCombo->selectedIndex() != match) {
                    zoomCombo->setSelectedIndex(match);
                }
            }
            return newui::SyncReturn::Handled;
        };

        // Menus: items are found by menu and item text (see tools/gen_newui.py).
        auto* menuBar = dynamic_cast<newui::MenuBar*>(frame.rootView().findView("menuBar"));
        // `menuName` may be a path such as "Object/Transform" for an item inside a submenu.
        auto onItem = [menuBar](const char* menuName, const char* text, std::function<void(newui::MenuItem&)> action) {
            if (menuBar == nullptr) {
                return;
            }
            std::string path = menuName;
            const std::vector<newui::MenuItem*>* level = &menuBar->menus();
            std::size_t start = 0;
            newui::MenuItem* menu = nullptr;
            while (start <= path.size()) {
                std::size_t slash = path.find('/', start);
                std::string part = path.substr(start, slash == std::string::npos ? std::string::npos : slash - start);
                menu = nullptr;
                for (newui::MenuItem* candidate : *level) {
                    if (candidate->text() == part) {
                        menu = candidate;
                    }
                }
                if (menu == nullptr) {
                    return;
                }
                level = &menu->children();
                if (slash == std::string::npos) {
                    break;
                }
                start = slash + 1;
            }
            for (newui::MenuItem* item : menu->children()) {
                if (item->text() == text) {
                    item->onClick += [action](newui::MenuItem& clicked) {
                        action(clicked);
                        return newui::SyncReturn::Handled;
                    };
                }
            }
        };

        // View menu: Zoom In/Out, Fit Page, Actual Size, Show Grid, Show Rulers.
        auto center = [canvas]() {
            newui::Rect client = canvas->getClientBounds();
            return newui::Point(client.width() * 0.5f, client.height() * 0.5f);
        };
        onItem("View", "Zoom In", [canvas, center](newui::MenuItem&) { canvas->zoomAt(center(), canvas->zoom() * 1.25f); });
        onItem("View", "Zoom Out", [canvas, center](newui::MenuItem&) { canvas->zoomAt(center(), canvas->zoom() / 1.25f); });
        onItem("View", "Fit Page", [canvas](newui::MenuItem&) { canvas->zoomToFit(); });
        onItem("View", "Actual Size", [canvas](newui::MenuItem&) { canvas->setZoom(1.0f); });
        onItem("View", "Show Grid", [canvas](newui::MenuItem& item) {
            canvas->setShowGrid(!canvas->showGrid());
            item.setChecked(canvas->showGrid());
        });
        onItem("View", "Show Rulers", [canvas](newui::MenuItem& item) {
            canvas->setShowRulers(!canvas->showRulers());
            item.setChecked(canvas->showRulers());
        });

        // Edit menu and the matching toolbar buttons (all act on the document's undo stack/selection).
        sketch::SketchDocument* doc = &document;
        std::function<void()> undo = [doc]() { doc->undoStack().undo(); };
        std::function<void()> redo = [doc]() { doc->undoStack().redo(); };
        std::function<void()> del = [doc]() { doc->deleteSelection(); };
        std::function<void()> duplicate = [doc]() { doc->duplicateSelection(12.0, 12.0); };
        onItem("Edit", "Undo", [undo](newui::MenuItem&) { undo(); });
        onItem("Edit", "Redo", [redo](newui::MenuItem&) { redo(); });
        onItem("Edit", "Delete", [del](newui::MenuItem&) { del(); });
        onItem("Edit", "Duplicate", [duplicate](newui::MenuItem&) { duplicate(); });
        onItem("Object/Transform", "Reset Bounding Box", [doc](newui::MenuItem&) { doc->resetBoundingBox(); });
        onItem("Edit", "Select All", [doc](newui::MenuItem&) { doc->selectAll(); });
        onItem("Edit", "Deselect", [doc](newui::MenuItem&) { doc->clearSelection(); });

        auto onButton = [&frame](const char* name, std::function<void()> action) {
            if (auto* button = dynamic_cast<newui::Control*>(frame.rootView().findView(name))) {
                button->onClick += [action](newui::Control&) {
                    action();
                    return newui::SyncReturn::Handled;
                };
            }
        };
        onButton("undoButton", undo);
        onButton("redoButton", redo);
        onButton("deleteButton", del);

        // Tool palette: radio behavior over the toggle buttons; the canvas tool and the buttons follow each other.
        struct ToolButton { const char* name; sketch::SketchTool tool; };
        static const ToolButton kTools[] = {
            {"selectTool", sketch::SketchTool::Select},
            {"directSelectTool", sketch::SketchTool::DirectSelect},
            {"rectangleTool", sketch::SketchTool::Rectangle},
            {"ellipseTool", sketch::SketchTool::Ellipse},
            {"lineTool", sketch::SketchTool::Line},
            {"penTool", sketch::SketchTool::Pen},
            {"pencilTool", sketch::SketchTool::Pencil},
            {"textTool", sketch::SketchTool::Text},
            {"gradientTool", sketch::SketchTool::Gradient},
            {"handTool", sketch::SketchTool::Hand},
            {"zoomTool", sketch::SketchTool::Zoom},
        };
        for (const ToolButton& entry : kTools) {
            if (auto* button = dynamic_cast<newui::ToolbarButton*>(frame.rootView().findView(entry.name))) {
                sketch::SketchTool tool = entry.tool;
                button->onCheckedChanged += [canvas, tool](newui::ToolbarButton& changed) {
                    if (changed.isChecked()) {
                        canvas->setTool(tool);
                    } else if (canvas->tool() == tool) {
                        changed.setChecked(true);  // a tool stays on until another replaces it
                    }
                    return newui::SyncReturn::Handled;
                };
            }
        }
        canvas->onToolChanged += [&frame](sketch::CanvasView& view) {
            for (const ToolButton& entry : kTools) {
                if (auto* button = dynamic_cast<newui::ToolbarButton*>(frame.rootView().findView(entry.name))) {
                    bool on = entry.tool == view.tool();
                    if (button->isChecked() != on) {
                        button->setChecked(on);
                    }
                }
            }
            return newui::SyncReturn::Handled;
        };

        // Status bar: first pane reports the selection count.
        document.onSelectionChanged += [status](sketch::SketchDocument& changed) {
            if (status != nullptr) {
                std::size_t count = changed.selection().size();
                status->setPaneText(0, count == 0 ? "Ready" : std::to_string(count) + (count == 1 ? " object selected" : " objects selected"));
            }
            return newui::SyncReturn::Handled;
        };
    }

    if (!startupPath.empty()) {
        // S4 replaces this with SketchDocument::load(); for now the path just shows in the title
        // bar and the first status pane so the command line is visibly honored.
        frame.setTitle("sketch - " + startupPath);
        if (auto* status = dynamic_cast<newui::StatusBar*>(frame.rootView().findView("statusBar"))) {
            status->setPaneText(0, "Opening " + startupPath + " (SVG loading arrives with S4)");
        }
    }

    if (checkTools) {
        // Headless test of the palette wiring: checking each tool button must switch the canvas tool
        // and leave exactly that one button checked.
        auto* canvas = dynamic_cast<sketch::CanvasView*>(frame.rootView().findView("canvas"));
        static const char* kNames[] = {"selectTool", "directSelectTool", "rectangleTool", "ellipseTool", "lineTool",
            "penTool", "pencilTool", "textTool", "gradientTool", "handTool", "zoomTool"};
        int failures = 0;
        for (const char* name : kNames) {
            auto* button = dynamic_cast<newui::ToolbarButton*>(frame.rootView().findView(name));
            if (button == nullptr || canvas == nullptr) {
                std::printf("FAIL %s: not found\n", name);
                ++failures;
                continue;
            }
            button->setChecked(true);
            int lit = 0;
            for (const char* other : kNames) {
                auto* b = dynamic_cast<newui::ToolbarButton*>(frame.rootView().findView(other));
                lit += (b != nullptr && b->isChecked()) ? 1 : 0;
            }
            std::printf("%s -> tool %d, %d button(s) checked%s\n", name, int(canvas->tool()), lit, lit == 1 ? "" : "  <-- FAIL");
            failures += lit == 1 ? 0 : 1;
        }
        return failures;
    }

    app.run();
    return 0;
}
