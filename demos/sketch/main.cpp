// sketch - vector editor demo (see demos/PLAN.md).
//
//   sketch.exe [file]            opens the window (and the file, when one is named)
//   sketch.exe --check           loads the layout, lays it out, prints the view tree (--depth=N, default 4) and exits
//   sketch.exe --check-newdoc    runs the New Document dialog's self-checks
//   sketch.exe --check-tools     drives the window headlessly and prints ok / FAIL per expectation; the exit code is the
//                                number of failures
//
// This file only starts the program. How the pieces fit together (model / views / controllers):
//   SketchDocument            the model - the artwork, its selection and undo history          (sketchdocument.h)
//   CanvasView, StylePanel    views - the drawing surface and the panels                       (canvasview.h, stylepanel.h)
//   sketch.newui              the rest of the views: menus, toolbars, palette, status bar      (Resources/, tools/gen_newui.py)
//   SketchDocumentController  the File commands: New / Open / Save, the questions and dialogs  (sketchcontroller.h)
//   SketchCommandController   every other command, by id                                       (sketchcommands.h)
//   SketchWindowController    binds the views to the model and the controllers                 (sketchwindow.h)

#include "newui/application.h"
#include "newui/bundle.h"
#include "newui/frame.h"
#include "newui/rootview.h"

#include "newdocumentdialog.h"
#include "sketchchecks.h"
#include "sketchdocument.h"
#include "sketchwindow.h"

#include <cstdio>
#include <string>
#include <typeinfo>

// Both generated by reflectgen - nothing calls them automatically for a standalone exe. newui's own classes first (sketch's classes
// derive from them), then sketch's.
extern void registerReflectionData();
extern void registerSketchReflection();

namespace {

    struct Options {
        std::string startupPath;
        bool check = false;
        bool checkNewDocument = false;
        bool checkTools = false;
        int checkDepth = 4;
    };

    Options parseOptions(int argc, char** argv) {
        Options options;
        for (int i = 1; i < argc; ++i) {
            std::string arg = argv[i];
            if (arg == "--check") {
                options.check = true;
            } else if (arg == "--check-tools") {
                options.checkTools = true;
            } else if (arg == "--check-newdoc") {
                options.checkNewDocument = true;
            } else if (arg.rfind("--depth=", 0) == 0) {
                options.checkDepth = std::stoi(arg.substr(8));
            } else if (options.startupPath.empty()) {
                options.startupPath = arg;
            }
        }
        return options;
    }

    // Prints the loaded view tree (class, name, bounds) down to maxDepth - what --check shows, to confirm sketch.newui loaded into the
    // structure the mockup describes and laid out sensibly.
    void dumpTree(const newui::View& view, int depth, int maxDepth) {
        const newui::Rect& b = view.bounds();
        std::printf("%*s%s \"%s\" [%.0f,%.0f %.0fx%.0f]%s\n", depth * 2, "", typeid(view).name(),
            view.name().c_str(), b.left(), b.top(), b.width(), b.height(), view.isVisible() ? "" : " (hidden)");
        if (depth >= maxDepth) {
            return;
        }
        for (const newui::SubView* child : view.childViews()) {
            dumpTree(*child, depth + 1, maxDepth);
        }
    }

    // --check: load, lay out, print the trees of the main window and of the New Document dialog (a separate Frame), and stop.
    int printLayouts(newui::Frame& frame, int depth) {
        frame.rootView().updateLayout();
        dumpTree(frame.rootView(), 0, depth);

        newui::Frame dialog;
        dialog.setName("newdocument");
        if (!newui::Bundle::instance().loadFrame(dialog)) {
            std::printf("sketch: could not load Resources/newdocument.newui\n");
            return 1;
        }
        std::printf("--- newdocument ---\n");
        dialog.rootView().updateLayout();
        dumpTree(dialog.rootView(), 0, depth);
        return 0;
    }
}

int main(int argc, char** argv) {
    registerReflectionData();
    registerSketchReflection();
    const Options options = parseOptions(argc, argv);

    newui::Frame frame;
    newui::Application& app = newui::Application::instance();
    app.setName("sketch");
    app.setFrame(&frame);

    // Bundle::loadFrame() resolves "Resources/<frame name>.newui" next to the exe; CMake copies demos/sketch/Resources there after each build.
    frame.setName("sketch");
    if (!newui::Bundle::instance().loadFrame(frame)) {
        std::printf("sketch: could not load Resources/sketch.newui\n");
        return 1;
    }
    if (options.checkNewDocument) {
        return sketch::NewDocumentDialog::check();
    }
    if (options.check) {
        return printLayouts(frame, options.checkDepth);
    }

    // The model, then the controller that wires it to the views (it lives as long as the window does).
    sketch::SketchDocument document;
    sketch::SketchWindowController window(frame, document);
    if (options.checkTools) {
        return sketch::runToolChecks(window);
    }
    window.start(options.startupPath);
    app.run();
    return 0;
}
